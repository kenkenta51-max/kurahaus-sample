"""Create the public GitHub Pages artifact without altering the local preview."""

from __future__ import annotations

import re
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "site-dist"
MARKER = OUTPUT / ".kurahaus-generated"
BASE_PATH = "/kurahaus-sample/"
SITE_URL = "https://kenkenta51-max.github.io" + BASE_PATH

PUBLIC_DIRECTORIES = (
    "assets",
    "company",
    "concept",
    "contact",
    "document",
    "faq",
    "housing",
    "modelhouse",
    "news",
    "privacy",
    "reserve",
    "sitemap",
    "staff",
    "voice",
    "works",
)
PUBLIC_FILES = (
    "404.html",
    "index.html",
    "remaining-forms.js",
    "robots.txt",
    "script.js",
    "sitemap.xml",
    "styles.css",
)

BANNER = (
    '<div class="portfolio-demo-banner" id="portfolio-demo" role="note">'
    "ポートフォリオ用の架空サイトです｜予約・お問い合わせは送信されません"
    "</div>"
)
BANNER_CSS = """

/* Portfolio-only disclosure; present on every published page. */
:root { --portfolio-demo-height: 32px; }
body { padding-top: var(--portfolio-demo-height); }
.site-header { top: var(--portfolio-demo-height); }
.mobile-menu { top: var(--portfolio-demo-height); }
.skip-link { top: calc(var(--portfolio-demo-height) + 12px); }
.portfolio-demo-banner {
  position: fixed;
  z-index: 2000;
  inset: 0 0 auto;
  display: flex;
  align-items: center;
  justify-content: center;
  min-height: var(--portfolio-demo-height);
  padding: 5px 12px;
  color: #fff;
  background: #25392e;
  font: 500 12px/1.4 "Noto Sans JP", "Yu Gothic", sans-serif;
  text-align: center;
}
@media (max-width: 480px) {
  :root { --portfolio-demo-height: 38px; }
  .portfolio-demo-banner { font-size: 11px; }
}
"""


def local_route(relative_path: Path) -> str:
    if relative_path.name == "404.html":
        return "404.html"
    if relative_path.name == "index.html":
        parent = relative_path.parent.as_posix()
        return "" if parent == "." else parent + "/"
    return relative_path.as_posix()


def transform_html(content: str, relative_path: Path) -> str:
    # Project Pages sites live below /kurahaus-sample/, unlike the local preview.
    content = re.sub(
        r'(?P<attribute>\b(?:href|src|poster|action)=["\'])(?P<path>/(?!/)[^"\']*)',
        lambda match: match["attribute"] + BASE_PATH + match["path"][1:],
        content,
    )
    content = content.replace("https://example.com/", SITE_URL)
    content = re.sub(r"<!-- TODO: 公開ドメイン確定後に[^>]*-->", "", content)

    # Fictional contact details must not launch real-world actions.
    content = re.sub(
        r'href="tel:[^"]+"',
        'href="#portfolio-demo" title="デモサイトのため電話は利用できません"',
        content,
    )
    content = re.sub(
        r'href="https://(?:www\.instagram\.com/|line\.me/|www\.youtube\.com/|maps\.google\.com/\?q=[^"]*)"',
        'href="#portfolio-demo" title="デモサイトのため外部リンクは利用できません"',
        content,
    )
    content = re.sub(r"<body(?P<attributes>[^>]*)>", lambda m: m.group(0) + BANNER, content, count=1)

    if relative_path.name != "404.html":
        canonical = SITE_URL + local_route(relative_path)
        tags = (
            f'<link rel="canonical" href="{canonical}" />'
            f'<meta property="og:url" content="{canonical}" />'
        )
        content = re.sub(r"</head>", tags + "</head>", content, count=1, flags=re.IGNORECASE)
    return content


def main() -> None:
    if OUTPUT.exists():
        if not MARKER.is_file() or OUTPUT.resolve().parent != ROOT.resolve():
            raise RuntimeError(f"Refusing to replace an unrecognized output directory: {OUTPUT}")
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    MARKER.write_text("Generated by scripts/build-pages.py\n", encoding="utf-8")

    for directory in PUBLIC_DIRECTORIES:
        shutil.copytree(ROOT / directory, OUTPUT / directory)
    for filename in PUBLIC_FILES:
        shutil.copy2(ROOT / filename, OUTPUT / filename)

    count = 0
    for page in OUTPUT.rglob("*.html"):
        relative_path = page.relative_to(OUTPUT)
        page.write_text(transform_html(page.read_text(encoding="utf-8"), relative_path), encoding="utf-8")
        count += 1

    css = OUTPUT / "styles.css"
    css.write_text(css.read_text(encoding="utf-8") + BANNER_CSS, encoding="utf-8")
    for filename in ("sitemap.xml", "robots.txt"):
        file = OUTPUT / filename
        text = file.read_text(encoding="utf-8").replace("https://example.com/", SITE_URL)
        text = re.sub(r"(?m)^# TODO: replace example\.com.*\n", "", text)
        file.write_text(text, encoding="utf-8")

    print(f"Prepared {count} HTML pages in {OUTPUT.name}")


if __name__ == "__main__":
    main()
